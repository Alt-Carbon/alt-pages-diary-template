/* Every section is one leaf. Moving one section turns one leaf. Jumping several
   turns each leaf in between, staggered, the way a thumb riffles through a pad,
   forward or back. The essay is a detail view and always turns as one leaf. */
function leavesBetween(from, id) {
  const a = idx(from), b = idx(id), forward = b > a;
  if (id === "essay" || from === "essay") return [forward ? { page: pageEls[from], back: b } : { page: pageEls[id], back: a }];
  const seq = [];
  if (forward) for (let j = a; j < b; j++) seq.push({ page: pageEls[PAGES[j].id], back: j + 1 });
  else for (let j = a - 1; j >= b; j--) seq.push({ page: pageEls[PAGES[j].id], back: j + 1 });
  return seq;
}
function turnTo(id, animate = true, onDone = () => {}) {
  if (!pageEls[id]) return;
  if (id === current) { onDone(); return; }
  const from = current, prev = pageEls[from], next = pageEls[id];
  const forward = !from || idx(id) > idx(from);
  const focusInPage = prev && prev.contains(document.activeElement);
  current = id;
  const settle = (landingBack = null) => {
    for (const p of Object.values(pageEls)) { p.classList.toggle("show", p === next); p.inert = p !== next; p.style.zIndex = p === next ? 2 : 0; }
    if (landingBack) {
      $("#lp").replaceChildren(...landingBack.childNodes);
      $("#lp").dataset.pageIndex = idx(id);
    } else if (Number($("#lp").dataset.pageIndex) !== idx(id)) {
      setLeft(id);
    }
    if (focusInPage) next.focus({ preventScroll: true });
  };
  if (!prev || !animate || reducedMotion() || matchMedia("(max-width:760px)").matches) { settle(); onDone(); return; }

  /* Forward: each leaf goes over from the right pile and its back is the next
     section's left page. Back: leaves lift off the left pile, top one first, and
     land on the right with the earlier right page on top. Only leaves in the air
     are strips: a leaf is built just before it moves, and when a leaf lands it
     becomes the pile (its back the left page, or its front the flat right page)
     and its strips go, because the browser stops sorting too many 3D layers. */
  const leaves = leavesBetween(from, id), k = leaves.length;
  const flat = forward ? next : prev;
  const duration = k === 1 ? MOTION.page : MOTION.leaf;
  const stagger = k === 1 ? 0 : Math.min(MOTION.stagger, (MOTION.riffle - duration) / (k - 1));
  const total = (k - 1) * stagger + duration;
  // Measure an incoming leaf without exposing its flat face above the current one.
  next.classList.add("show"); next.style.zIndex = 0; prev.style.zIndex = 2;
  const W = $(".face.front", flat).getBoundingClientRect().width;
  const stripCount = k === 1 ? 24 : 12;   // a riffle moves fast; fewer strips keep it smooth
  const sheets = [];
  const build = o => {
    const s = buildSheet(leaves[o].page, leaves[o].back, W, stripCount);
    if (k > 1) s.root.classList.add("riffle");
    s.root.style.transform = `translateZ(${(k - o) * .03 + .001}px)`;   // the next leaf to move rests on top
    s.apply(forward ? 0 : 1);
    return sheets[o] = s;
  };
  let topRight = prev, tintR = $(".under", prev), tintL = $("#left .under");
  const land = o => {   // an intermediate leaf joins the pile it landed on
    const s = sheets[o]; s.remove(); s.gone = true;
    if (forward) { $("#lp").replaceChildren(...s.back.childNodes); $("#lp").dataset.pageIndex = leaves[o].back; }
    else { const p = leaves[o].page; topRight.style.zIndex = 0; p.classList.add("show"); p.inert = true; p.style.zIndex = 2; topRight = p; tintR = $(".under", p); }
  };
  const paintAll = elapsed => {
    let shadeR = 0, shadeL = 0;
    for (let o = 0; o < k; o++) {
      const delay = o * stagger;
      if (!sheets[o]) { if (elapsed < delay - stagger) break; build(o); }
      const s = sheets[o];
      if (s.gone) continue;
      const u = Math.max(0, Math.min(1, (elapsed - delay) / duration)), t = easeInOut(u);
      s.apply(forward ? t : 1 - t);
      if (u >= 1 && o < k - 1) { land(o); continue; }
      const sh = Math.sin(t * Math.PI); shadeR = Math.max(shadeR, sh * (1 - t)); shadeL = Math.max(shadeL, sh * t);
    }
    tintR.style.opacity = shadeR * .9; tintL.style.opacity = shadeL * .9;
  };
  paintAll(0);
  let done = false, landing = false, frame = null, cancel = () => {};
  let dissolve = [];
  const cleanup = (continueRoute) => {
    if (done) return;
    done = true;
    cancelAnimationFrame(frame); cancel();
    dissolve.forEach(animation => animation.cancel());
    sheets.forEach(s => s.remove()); finishTurn = null;
    if (continueRoute) onDone();
  };
  finishTurn = (continueRoute = false) => {
    if (done) return;
    if (landing) { cleanup(continueRoute); return; }
    landing = true;
    cancelAnimationFrame(frame); cancel();
    // Land the last leaf on its exact plane and DOM; every other leaf is already the pile or never left it.
    const last = sheets[k - 1];
    sheets.forEach((s, o) => { if (o < k - 1) s.remove(); });
    last?.apply(forward ? 1 : 0);
    settle(forward && last ? last.back : null);
    tintR.style.opacity = 0; tintL.style.opacity = 0;
    if (!continueRoute || !last) { cleanup(false); if (continueRoute) onDone(); return; }
    // Let the static sheet paint, then dissolve only the planar strip surfaces.
    // Fading the 3D parent itself would flatten the bend and cause another snap.
    frame = requestAnimationFrame(() => {
      frame = requestAnimationFrame(() => {
        if (done) return;
        dissolve = [...last.root.querySelectorAll(".cut")].map(surface =>
          surface.animate([{opacity:1}, {opacity:0}], {duration:80, easing:"linear", fill:"forwards"}));
        dissolve[0].onfinish = () => cleanup(true);
      });
    });
  };
  // Give the browser a paint to prepare the new leaves before the first movement.
  // This also separates cancelling the entrance from starting a page turn.
  frame = requestAnimationFrame(() => {
    frame = requestAnimationFrame(() => {
      if (done) return;
      prev.inert = true;
      prev.classList.toggle("show", !forward);
      next.classList.toggle("show", forward);
      flat.style.zIndex = 2;
      if (!forward) setLeft(id);
      cancel = run(total, paintAll, () => finishTurn?.(true));
    });
  });
}
/* Jump to the requested section with one interruptible turn. */
function flipTo(id, animate = true, push = true) {
  if (!pageEls[id]) return;
  finishEntry?.();
  const version = ++navigationVersion;
  finishTurn?.();
  destination = id;
  if (push && matchMedia("(max-width:760px)").matches) window.scrollTo({top: 0, behavior: "instant"});
  setChrome(id);
  if (push && location.hash !== "#" + id) history.pushState(null, "", "#" + id);
  const book = $("#book");
  const canAnimate = animate && !reducedMotion() && !matchMedia("(max-width:760px)").matches;
  book.setAttribute("aria-busy", String(canAnimate && current !== null && current !== id));
  const complete = () => { if (version !== navigationVersion) return; book.setAttribute("aria-busy", "false"); setChrome(id); };
  turnTo(id, canAnimate, complete);
}
function movePage(direction, animate = true) {
  if ((destination || current) === "essay") return flipTo("writing", animate);
  const target = Math.max(0, Math.min(N_PAGES - 1, idx(destination || current) + direction));
  flipTo(SECTIONS[target].id, animate);
}

